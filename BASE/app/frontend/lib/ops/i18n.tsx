const DICS: Record<Lang, Dic> = { es, en, pt };

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (clave: string, params?: Record<string, string | number>) => string;
  locale: string;
  fmtN: (n: number, dec?: number) => string;
  fmtMes: (yyyymm: string) => string;
};

const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es");

  useEffect(() => {
    const guardado = localStorage.getItem(CLAVE) as Lang | null;
    if (guardado && DICS[guardado]) setLangState(guardado);
    else {
      const nav = navigator.language.slice(0, 2) as Lang;
      if (DICS[nav]) setLangState(nav);
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem(CLAVE, l);
    document.documentElement.lang = l;
  }, []);

  const value = useMemo<Ctx>(() => {
    const locale = LOCALES[lang];
    return {
      lang, setLang, locale,
      t: (clave, params) => {
        let s = DICS[lang][clave] ?? DICS.es[clave] ?? clave;
        for (const [k, v] of Object.entries(params ?? {})) {
          s = s.replaceAll(`{${k}}`, String(v));
        }
        return s;
      },
      fmtN: (n, dec = 0) => n.toLocaleString(locale, {
        minimumFractionDigits: dec, maximumFractionDigits: dec }),
      fmtMes: (yyyymm) => {
        // compacto a propósito ("sep 25"): el formato con año de Intl mete
        // conectores largos en pt/es ("set. de 25") y desborda los ejes.
        const [y, m] = yyyymm.split("-").map(Number);
        const mes = new Date(y, m - 1, 1)
          .toLocaleDateString(locale, { month: "short" })
          .replace(".", "");
        return `${mes} ${String(y).slice(2)}`;
      },
    };
  }, [lang, setLang]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n requiere <I18nProvider>");
  return ctx;
}
